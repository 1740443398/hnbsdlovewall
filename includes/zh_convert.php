if (!function_exists('lwZhReverseTable')) {
    /** 繁 → 简：把简繁表反过来（一个字可能有多个简体来源，取第一个）。 */
    function lwZhReverseTable(): array
    {
        static $r = null;
        if ($r !== null) {
            return $r;
        }
        $r = [];
        foreach (lwZhTable() as $simp => $trad) {
            if (!isset($r[$trad])) {
                $r[$trad] = $simp;
            }
        }
        return $r;
    }
}

if (!function_exists('lwConvertZh')) {
    /**
     * 简繁互转（逐字替换字表，不动非汉字）。
     *
     * @param string $text 原文
     * @param string $to   'trad' 简→繁 / 'simp' 繁→简
     */
    function lwConvertZh(string $text, string $to): string
    {
        if ($text === '') {
            return $text;
        }
        $table = ($to === 'simp') ? lwZhReverseTable() : lwZhTable();
        if (!$table) {
            return $text;
        }
        // strtr 一次性替换全部匹配键，按最长匹配优先，且不会二次替换已转过的字
        return strtr($text, $table);
    }
}

if (!function_exists('lwDetectZhVariant')) {
    /**
     * 粗略判断文本是简体还是繁体（按特征字计数）。
     * @return string 'simp' | 'trad' | 'unknown'
     */
    function lwDetectZhVariant(string $text): string
    {
        if ($text === '') {
            return 'unknown';
        }
        $tradChars = implode('', array_values(lwZhTable()));
        $simpChars = implode('', array_keys(lwZhTable()));
        if ($tradChars === '' || $simpChars === '') {
            return 'unknown';
        }
        $t = preg_match_all('/[' . preg_quote($tradChars, '/') . ']/u', $text);
        $s = preg_match_all('/[' . preg_quote($simpChars, '/') . ']/u', $text);
        if ($t === false || $s === false) {
            return 'unknown';
        }
        if ($t > $s) return 'trad';
        if ($s > $t) return 'simp';
        return 'unknown';
    }
