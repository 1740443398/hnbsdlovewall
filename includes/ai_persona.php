            $L[] = '6. 当前是游客只读模式。涉及「我的帖子/我的收藏/我的通知/我的私信/我的签到」或任何写操作时，先温和说明需要注册登录，再给 /pages/register.php 的链接；不要嘲讽、不要反复催促。';
        }

        if ($blocks) {
            $L[] = '';
            $L[] = '【站点实时数据｜服务器在本次提问时现取，可信；回答涉及本站时必须以这些为准，不要凭印象编造】';
