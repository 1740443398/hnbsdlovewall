<?php
/**
 * AI 助手 · 人设与系统提示词
 *
 * 单独成文件的原因：提示词是 AI 行为的**唯一真源**，也是最需要被测试的东西
 * （身份是否被正确注入、能力边界有没有写全、游客规则有没有生效、有没有把禁止清单漏掉）。
 * 抽成函数后可以直接单测，不必真的去调一次模型。
 *
 * 安全前提：本函数的**所有**输入都必须是服务端自己算出来的（会话 + 站点设置），
